import type { DemoStage } from './demo'

export interface GuideStep {
  /** 고유 키 — 목차 점프나 디버깅에 쓴다 */
  id: string
  /** 발표 메모의 절 번호(1~16) — 진행률 표시에 쓴다 */
  slide: number
  /** 슬라이드 이름 — 화면 전환 시 안내 카드 위에 적는다 */
  slideLabel: string
  /** 이동할 라우트. 없으면 지금 화면에 그대로 머문다 */
  path?: string
  /**
   * 하이라이트할 자리 — `[data-tour="값"]` 로 찾는다.
   * 없으면 화면 가운데 안내 카드만 뜬다(인트로 · 마무리 슬라이드).
   */
  selector?: string
  /** 카드 제목 — 그 자리에서 짚는 한 마디 */
  title: string
  /** 카드 본문 — 그 포인트에서 짚어야 할 한두 문장 */
  body: string
  /**
   * 이 스텝의 화면이 성립하려면 처리가 어디까지 끝나 있어야 하는가.
   *
   * 입고 이력은 입고를 해야 한 줄이 생기고, 배정된 개체 표는 예약을 해야 채워진다.
   * 선언해 두면 가이드가 스토어 액션으로 그 상태를 만든 뒤 화면을 보여준다.
   */
  demo?: DemoStage
  /**
   * 강조한 자리가 버튼이라, 눌리는 모습을 보여줘야 하는가.
   *
   * `demo` 로 실제로 상태가 바뀌는 스텝에서만 켠다 — 바뀔 것이 없는데 눌리는 시늉을
   * 하면 청중이 화면 어딘가가 바뀐 줄 알고 찾는다.
   */
  press?: boolean
  /**
   * 같은 앵커에 여러 자리가 걸려도 첫 번째만 짚는다.
   *
   * `purchase.row.*` 처럼 "이 성격의 줄들을 모두 보라"는 의도로 여러 개를 짚는
   * 스텝과 달리, 배지 하나의 생김새만 보여주면 되는 스텝(`items.inactiveBadge` 등)은
   * 목록 상태에 따라 우연히 여러 줄에 같은 배지가 나타날 수 있다. 이때 기본 동작대로
   * 전부를 감싸면 그 줄 사이 간격만큼 포커스가 비정상적으로 커진다.
   */
  focusFirstMatch?: boolean
}
